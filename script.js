let generatedPDF = null;

function generateCertificate() {
    if (allBadgesEarned()) {
        alert(currentLanguage === 'en'
            ? 'Earn all the badges first before generating your certificate!'
            : 'Kunin muna lahat ng badge bago makagawa ng certificate!');
        return;
    }

    const name = document.getElementById('child-name').value.trim();
    const sanitizedName = name.replace(/[^a-zA-Z\s\-']/g, '');

    if (!sanitizedName) {
        alert(currentLanguage === 'en'
            ? 'Please enter a valid name (letters only)!'
            : 'Pakiinput ang tamang pangalan (mga titik lamang)!');
        return;
    }

    const certificateDisplay = document.getElementById('certificate-display');
    certificateDisplay.innerHTML = '';

    const borderBox = document.createElement('div');
    borderBox.style.cssText = `
        border: 8px solid #3498db;
        border-radius: 15px;    
        width: 100%;
        height: 100%;
        box-sizing: border-box;
        padding: 20mm;
        display: flex;
        flex-direction: column;
        align-items: center;
        justify-content: center;
    `;

    const title = document.createElement('h2');
    title.style.cssText = 'color: #3498db; font-size: 30pt; margin: 10mm 0 6mm 0; text-align: center;';
    title.textContent = '🏆 Certificate of Achievement 🏆';

    const subtitle = document.createElement('h3');
    subtitle.style.cssText = 'font-size: 18pt; margin: 0 0 8mm 0; color: #2c3e50; text-align: center;';
    subtitle.textContent = 'Hygiene Hero Award';

    const intro = document.createElement('p');
    intro.style.cssText = 'font-size: 14pt; margin: 0 0 4mm 0; color: #2c3e50; text-align: center;';
    intro.textContent = 'This certificate is proudly presented to:';

    const nameDisplay = document.createElement('h1');
    nameDisplay.style.cssText = 'color: #e74c3c; font-size: 34pt; margin: 8mm 0; text-decoration: underline; text-align: center;';
    nameDisplay.textContent = sanitizedName;

    const description = document.createElement('p');
    description.style.cssText = 'font-size: 13pt; margin: 0 0 12mm 0; line-height: 1.6; color: #2c3e50; text-align: center;';
    description.innerHTML = 'For successfully learning about water hygiene and handwashing<br>and becoming a true Hygiene Hero!';

    const dateP = document.createElement('p');
    dateP.style.cssText = 'margin-top: 10mm; font-size: 11pt; color: #7f8c8d; text-align: center;';
    dateP.textContent = `Date: ${new Date().toLocaleDateString()}`;

    borderBox.appendChild(title);
    borderBox.appendChild(subtitle);
    borderBox.appendChild(intro);
    borderBox.appendChild(nameDisplay);
    borderBox.appendChild(description);
    borderBox.appendChild(dateP);

    certificateDisplay.appendChild(borderBox);
    certificateDisplay.classList.add('show');

    html2canvas(certificateDisplay, { scale: 2 }).then(canvas => {
        const imgData = canvas.toDataURL("image/png");
        const pdf = new jspdf.jsPDF("l", "mm", "a4");

        const pageWidth = pdf.internal.pageSize.getWidth();
        const pageHeight = pdf.internal.pageSize.getHeight();

        const marginX = 10;
        const marginY = 10;
        const imgWidth = pageWidth - marginX * 2;
        const imgHeight = (canvas.height * imgWidth) / canvas.width;

        let position = marginY;
        if (imgHeight < pageHeight - marginY * 2) {
            position = (pageHeight - imgHeight) / 2;
        }

        pdf.addImage(imgData, "PNG", marginX, position, imgWidth, imgHeight);

        generatedPDF = pdf;
    });
}

function downloadCertificate() {
    if (generatedPDF) {
        const name = document.getElementById('child-name').value.trim() || "certificate";
        generatedPDF.save(`${name}_certificate.pdf`);
    } else {
        alert("Please generate the certificate first.");
    }
}

