// Memory Game
function initializeMemoryGame() {
    const memoryGameContainer = document.getElementById('memory-game');
    const scoreElement = document.getElementById('memory-score');
    const resetButton = document.getElementById('reset-memory');
    
    const symbols = ['🧼', '💧', '🦠', '🤲', '🚿', '🧽'];
    
    function createMemoryGame() {
        memoryCards = [...symbols, ...symbols].sort(() => Math.random() - 0.5);
        memoryGameContainer.innerHTML = '';
        flippedCards = [];
        canFlip = true;
        memoryScore = 0;
        scoreElement.textContent = memoryScore;
        
        memoryCards.forEach((symbol, index) => {
            const card = document.createElement('div');
            card.className = 'memory-card';
            card.dataset.symbol = symbol;
            card.dataset.index = index;
            card.addEventListener('click', flipCard);
            memoryGameContainer.appendChild(card);
        });
    }
    
    function flipCard(e) {
        const card = e.target;
        
        if (!canFlip || card.classList.contains('flipped') || card.classList.contains('matched')) {
            return;
        }
        
        card.classList.add('flipped');
        card.textContent = card.dataset.symbol;
        flippedCards.push(card);
        
        if (flippedCards.length === 2) {
            canFlip = false;
            
            setTimeout(() => {
                if (flippedCards[0].dataset.symbol === flippedCards[1].dataset.symbol) {
                    flippedCards.forEach(card => {
                        card.classList.add('matched');
                    });
                    memoryScore++;
                    scoreElement.textContent = memoryScore;
                    
                    if (memoryScore === 6) {
                        setTimeout(() => {
                            showAlertModal(
                                currentLanguage === 'en' ? 'Amazing memory!' : 'Kamangha-manghang memorya!',
                                currentLanguage === 'en'
                                    ? 'You found all pairs!'
                                    : 'Nahanap mo ang lahat ng pares!'
                            );
                            earnBadge('badge-memory-champ');
                        }, 500);
                    }
                } else {
                    flippedCards.forEach(card => {
                        card.classList.remove('flipped');
                        card.textContent = '';
                    });
                }
                
                flippedCards = [];
                canFlip = true;
            }, 1000);
        }
    }
    
    resetButton.addEventListener('click', createMemoryGame);
    createMemoryGame();
}

